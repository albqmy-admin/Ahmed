  ON public.albugmi2_service_categories FOR SELECT TO anon, authenticated
  USING (active IS TRUE);

DROP POLICY IF EXISTS albugmi2_services_public_read ON public.albugmi2_services;
CREATE POLICY albugmi2_services_public_read
  ON public.albugmi2_services FOR SELECT TO anon, authenticated
  USING (
    active IS TRUE
    AND EXISTS (
      SELECT 1 FROM public.albugmi2_service_categories AS category
      WHERE category.id = albugmi2_services.category_id AND category.active IS TRUE
    )
  );

DROP POLICY IF EXISTS albugmi2_offers_public_read ON public.albugmi2_offers;
CREATE POLICY albugmi2_offers_public_read
  ON public.albugmi2_offers FOR SELECT TO anon, authenticated
  USING (
    active IS TRUE
    AND (valid_from IS NULL OR valid_from <= current_date)
    AND (valid_until IS NULL OR valid_until >= current_date)
  );

CREATE OR REPLACE FUNCTION public.albugmi2_admin_analytics_summary()
RETURNS jsonb
LANGUAGE sql
SECURITY INVOKER
SET search_path = ''
AS $function$
  SELECT pg_catalog.jsonb_build_object(
    'totalVisits', (SELECT pg_catalog.count(*) FROM public.albugmi2_analytics WHERE event_type = 'page_view' AND created_at >= now() - interval '30 days'),
    'serviceClicks', (SELECT pg_catalog.count(*) FROM public.albugmi2_analytics WHERE event_type = 'service_click' AND created_at >= now() - interval '30 days'),
    'offerClicks', (SELECT pg_catalog.count(*) FROM public.albugmi2_analytics WHERE event_type = 'offer_click' AND created_at >= now() - interval '30 days'),
    'searches', (SELECT pg_catalog.count(*) FROM public.albugmi2_analytics WHERE event_type = 'search' AND created_at >= now() - interval '30 days'),
    'daily', COALESCE((
      SELECT pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object('day', daily.day, 'visits', daily.visits, 'serviceClicks', daily.service_clicks, 'offerClicks', daily.offer_clicks, 'searches', daily.searches) ORDER BY daily.day)
      FROM (
        SELECT (event.created_at AT TIME ZONE 'Asia/Riyadh')::date AS day,
          pg_catalog.count(*) FILTER (WHERE event.event_type = 'page_view') AS visits,
          pg_catalog.count(*) FILTER (WHERE event.event_type = 'service_click') AS service_clicks,
          pg_catalog.count(*) FILTER (WHERE event.event_type = 'offer_click') AS offer_clicks,
          pg_catalog.count(*) FILTER (WHERE event.event_type = 'search') AS searches
        FROM public.albugmi2_analytics AS event
        WHERE event.created_at >= now() - interval '7 days'
        GROUP BY 1 ORDER BY 1
      ) AS daily
    ), '[]'::jsonb),
    'serviceClicksByService', COALESCE((
      SELECT pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object('serviceId', service.id, 'label', service.name, 'count', COALESCE(clicks.count, 0)) ORDER BY category.sort_order, service.sort_order)
      FROM public.albugmi2_services AS service
      JOIN public.albugmi2_service_categories AS category ON category.id = service.category_id
      LEFT JOIN (
        SELECT service_id, pg_catalog.count(*) AS count
        FROM public.albugmi2_analytics
        WHERE event_type = 'service_click' AND created_at >= now() - interval '30 days' AND service_id IS NOT NULL
        GROUP BY service_id
      ) AS clicks ON clicks.service_id = service.id
    ), '[]'::jsonb),
    'topServices', COALESCE((
      SELECT pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object('label', popular.label, 'count', popular.count) ORDER BY popular.count DESC)
      FROM (SELECT label, pg_catalog.count(*) AS count FROM public.albugmi2_analytics WHERE event_type = 'service_click' AND created_at >= now() - interval '30 days' GROUP BY label ORDER BY count DESC LIMIT 5) AS popular
    ), '[]'::jsonb),
    'topOffers', COALESCE((
      SELECT pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object('label', popular.label, 'count', popular.count) ORDER BY popular.count DESC)
      FROM (SELECT label, pg_catalog.count(*) AS count FROM public.albugmi2_analytics WHERE event_type = 'offer_click' AND created_at >= now() - interval '30 days' GROUP BY label ORDER BY count DESC LIMIT 5) AS popular
    ), '[]'::jsonb),
    'topSearches', COALESCE((
      SELECT pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object('label', popular.search_term, 'count', popular.count) ORDER BY popular.count DESC)
      FROM (SELECT search_term, pg_catalog.count(*) AS count FROM public.albugmi2_analytics WHERE event_type = 'search' AND created_at >= now() - interval '30 days' GROUP BY search_term ORDER BY count DESC LIMIT 5) AS popular
    ), '[]'::jsonb)
  );
$function$;
REVOKE ALL ON FUNCTION public.albugmi2_admin_analytics_summary() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.albugmi2_admin_analytics_summary() TO service_role;

