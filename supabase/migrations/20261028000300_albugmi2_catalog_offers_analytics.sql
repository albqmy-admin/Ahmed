-- مكتب البقمي 2: dynamic catalogue, offers and privacy-minimal analytics.
-- Additive: preserves the legacy request table and every existing row.

CREATE TABLE IF NOT EXISTS public.albugmi2_service_categories (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL UNIQUE CHECK (char_length(btrim(name)) BETWEEN 2 AND 120),
  kicker text NOT NULL DEFAULT '' CHECK (char_length(kicker) <= 80),
  description text NOT NULL DEFAULT '' CHECK (char_length(description) <= 500),
  icon_key text NOT NULL DEFAULT 'transport' CHECK (icon_key IN ('transport', 'insurance', 'vehicles', 'digital')),
  sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN 0 AND 10000),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.albugmi2_services (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  category_id uuid NOT NULL REFERENCES public.albugmi2_service_categories(id) ON DELETE RESTRICT,
  name text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 2 AND 150),
  description text NOT NULL DEFAULT '' CHECK (char_length(description) <= 500),
  sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN 0 AND 10000),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT albugmi2_services_category_name_unique UNIQUE (category_id, name)
);

CREATE TABLE IF NOT EXISTS public.albugmi2_offers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 2 AND 120),
  description text NOT NULL DEFAULT '' CHECK (char_length(description) <= 800),
  discount_label text NOT NULL DEFAULT '' CHECK (char_length(discount_label) <= 50),
  valid_from date,
  valid_until date,
  image_path text CHECK (image_path IS NULL OR (char_length(image_path) <= 300 AND image_path LIKE 'offers/%')),
  service_id uuid REFERENCES public.albugmi2_services(id) ON DELETE SET NULL,
  sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN 0 AND 10000),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT albugmi2_offers_valid_dates CHECK (valid_from IS NULL OR valid_until IS NULL OR valid_from <= valid_until)
);

CREATE TABLE IF NOT EXISTS public.albugmi2_analytics (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type text NOT NULL CHECK (event_type IN ('page_view', 'service_click', 'offer_click', 'search')),
  label text NOT NULL CHECK (char_length(btrim(label)) BETWEEN 1 AND 160),
  service_id uuid REFERENCES public.albugmi2_services(id) ON DELETE SET NULL,
  offer_id uuid REFERENCES public.albugmi2_offers(id) ON DELETE SET NULL,
  search_term text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT albugmi2_analytics_search_rules CHECK (
    (event_type = 'search' AND search_term IS NOT NULL
      AND char_length(btrim(search_term)) BETWEEN 2 AND 100
      AND search_term !~* '[[:alnum:]._%+-]+@[[:alnum:].-]+[.][[:alpha:]]{2,}'
      AND search_term !~ '[+()0-9٠-٩۰-۹ -]{8,}')
    OR (event_type <> 'search' AND search_term IS NULL)
  ),
  CONSTRAINT albugmi2_analytics_entity_rules CHECK (
    (event_type = 'service_click' AND offer_id IS NULL)
    OR (event_type = 'offer_click' AND service_id IS NULL)
    OR (event_type IN ('page_view', 'search') AND service_id IS NULL AND offer_id IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS albugmi2_services_category_sort_idx
  ON public.albugmi2_services (category_id, sort_order, created_at);
CREATE INDEX IF NOT EXISTS albugmi2_offers_active_dates_idx
